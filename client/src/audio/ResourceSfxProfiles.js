export function hashResourceKey(resourceKey = '') {
  let h = 2166136261 | 0;
  const s = String(resourceKey || '');
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function getResourceSfxProfile(resourceKey = '') {
  const key = String(resourceKey || '').trim();
  if (RESOURCE_SFX_PROFILES[key]) return RESOURCE_SFX_PROFILES[key];
  const h = hashResourceKey(key);
  const groups = ['metal', 'ice', 'bio', 'exotic', 'science', 'tech', 'energy', 'crystal', 'component'];
  const group = groups[h % groups.length];
  const base = 260 + (h % 520);
  return {
    key,
    group,
    base,
    second: base * (1.18 + ((h >> 3) % 8) * 0.018),
    low: base * 0.5,
    amp: 0.026 + ((h >> 7) % 7) * 0.002,
    color: group
  };
}
